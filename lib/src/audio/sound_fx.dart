/// Sound effects of the game. Each value maps to `assets/audio/<file>.wav`,
/// produced by `tool/generate_sounds.py`.
enum Sfx {
  reveal('reveal'),
  flag('flag'),
  boom('boom'),
  win('win'),

  /// The garden level went up.
  levelUp('level_up'),

  /// A faster (or first) best time.
  newBest('new_best'),

  /// The daily garden was finished.
  daily('daily');

  const Sfx(this.file);

  final String file;

  String get asset => 'assets/audio/$file.wav';
}

/// Background music backend; tests substitute a recorder.
abstract class MusicPlayer {
  /// Starts the loop from the top. Completes with false if it could not
  /// start (for example the browser autoplay policy).
  Future<bool> start(String asset, double volume);

  /// Pauses, keeping the position where the backend can.
  void pause();

  /// Continues after [pause]. Completes with false if refused.
  Future<bool> resume();

  void stop();
}

/// Web: a looping HTML audio element. Native: `startLoop` / `stopLoop` on the
/// `tiny_mines/audio` channel (native pause restarts the loop on resume).
class PlatformMusicPlayer implements MusicPlayer {
  PlatformMusicPlayer({WebSound? web}) : _web = web ?? WebSound();

  static const MethodChannel _channel = MethodChannel('tiny_mines/audio');

  final WebSound _web;
  String? _asset;
  double _volume = 0;

  @override
  Future<bool> start(String asset, double volume) {
    _asset = asset;
    _volume = volume;
    if (kIsWeb) return _web.loop(asset, volume);
    return _invoke('startLoop', {'asset': asset, 'volume': volume});
  }

  @override
  void pause() {
    if (kIsWeb) {
      _web.pauseLoop();
    } else {
      _invoke('stopLoop');
    }
  }

  @override
  Future<bool> resume() {
    if (kIsWeb) return _web.resumeLoop();
    final asset = _asset;
    if (asset == null) return Future<bool>.value(false);
    return _invoke('startLoop', {'asset': asset, 'volume': _volume});
  }

  @override
  void stop() {
    if (kIsWeb) {
      _web.stopLoop();
    } else {
      _invoke('stopLoop');
    }
  }

  Future<bool> _invoke(String method, [Object? arguments]) async {
    try {
      await _channel.invokeMethod<void>(method, arguments);
      return true;
    } catch (_) {
      // MissingPluginException / PlatformException: music is optional.
      return false;
    }
  }
}

/// Backend that actually makes noise; tests substitute a recorder.
abstract class SoundPlayer {
  void play(String asset, double volume);

  void dispose();
}

/// Web: HTML audio elements. Native: the `tiny_mines/audio` channel.
/// Every failure is swallowed so audio can never block input.
class PlatformSoundPlayer implements SoundPlayer {
  static const MethodChannel _channel = MethodChannel('tiny_mines/audio');

  final WebSound _web = WebSound();

  @override
  void play(String asset, double volume) {
    if (kIsWeb) {
      _web.play(asset, volume);
      return;
    }
    _invoke('play', <String, Object>{'asset': asset, 'volume': volume});
  }

  @override
  void dispose() {
    if (!kIsWeb) _invoke('disposeAudio');
  }

  void _invoke(String method, [Object? arguments]) {
    try {
      unawaited(
        _channel
            .invokeMethod<void>(method, arguments)
            .then<void>(
              (_) {},
              onError: (Object _) {
                // MissingPluginException / PlatformException: audio is optional.
              },
            ),
      );
    } catch (_) {}
  }
}

/// Plays short sound effects and the background music loop, and owns the
/// persisted mute switch (one switch for both).
///
/// Effective mute = the player's own toggle OR the portal asking for silence
/// (`GamePlatform.isAudioMuted`).
///
/// Music has a wanted state ([startMusic] / [stopMusic]) separate from
/// whether it is actually playing: mute, a hidden app or tab, and (on web) a
/// missing first user input all hold it back until they clear.
class SoundFx extends ChangeNotifier {
  SoundFx({
    this.platform = const NoopGamePlatform(),
    SoundPlayer? player,
    MusicPlayer? music,
    Future<SharedPreferences> Function()? preferences,
    bool? requiresUserInput,
  }) : _player = player ?? PlatformSoundPlayer(),
       _music = music ?? (player == null ? PlatformMusicPlayer() : null),
       _requiresUserInput = requiresUserInput ?? kIsWeb,
       _preferences = preferences ?? SharedPreferences.getInstance;

  /// Generated by `tool/generate_sounds.py` (16 kHz mono, seamless loop).
  static const String musicAsset = 'assets/audio/music_loop.wav';
  static const double musicVolume = 0.4;

  /// `shared_preferences` key of the user's mute choice (default: sound on).
  static const String mutedKey = 'sound_muted_v1';

  static const double _volume = 0.7;

  final GamePlatform platform;
  final SoundPlayer _player;

  /// Null when a test injects only an effects player: no music then.
  final MusicPlayer? _music;
  final bool _requiresUserInput;
  final Future<SharedPreferences> Function() _preferences;

  bool _musicWanted = false;
  bool _musicPlaying = false;
  bool _musicStarting = false;
  // The loop was started once and can be resumed.
  bool _musicStarted = false;
  bool _appVisible = true;
  bool _userInteracted = false;

  bool _userMuted = false;
  bool _touched = false;
  bool _disposed = false;

  /// The player's own choice, shown by the toggle button.
  bool get userMuted => _userMuted;

  /// Whether nothing is audible right now.
  bool get muted => _userMuted || _platformMuted;

  bool get _platformMuted {
    try {
      return platform.isAudioMuted;
    } catch (_) {
      return false;
    }
  }

  /// Reads the stored choice; a storage failure keeps sound on.
  Future<void> load() async {
    try {
      final stored = (await _preferences()).getBool(mutedKey);
      // A toggle made while the read was pending wins.
      if (_touched || _disposed || stored == null || stored == _userMuted) {
        return;
      }
      _userMuted = stored;
      notifyListeners();
      _applyMusic();
    } catch (_) {}
  }

  Future<void> setUserMuted(bool value) async {
    _touched = true;
    if (value != _userMuted) {
      _userMuted = value;
      if (!_disposed) notifyListeners();
      _applyMusic();
    }
    try {
      await (await _preferences()).setBool(mutedKey, value);
    } catch (_) {}
  }

  Future<void> toggle() => setUserMuted(!_userMuted);

  /// Fire-and-forget; silent when muted, never throws.
  void play(Sfx sfx) {
    if (_disposed || !_appVisible || muted) return;
    try {
      _player.play(sfx.asset, _volume);
    } catch (_) {}
  }

  /// True while the music loop is (believed to be) audible.
  bool get isMusicPlaying => _musicPlaying;

  /// True after [startMusic] until [stopMusic], even while held back.
  bool get isMusicWanted => _musicWanted;

  /// Requests background music. It plays once nothing holds it back.
  void startMusic() {
    _musicWanted = true;
    _applyMusic();
  }

  /// Stops the music and forgets the request.
  void stopMusic() {
    _musicWanted = false;
    _applyMusic();
  }

  /// Call when the app or browser tab is hidden or shown again.
  void setAppVisible(bool visible) {
    if (_appVisible == visible) return;
    _appVisible = visible;
    _applyMusic();
  }

  /// Call on pointer or key input. Browsers only allow music after the first
  /// one; a request made earlier starts now.
  void onUserInput() {
    if (_userInteracted) {
      // Retry a loop the browser refused earlier.
      if (_musicWanted && !_musicPlaying) _applyMusic();
      return;
    }
    _userInteracted = true;
    _applyMusic();
  }

  /// Call after the platform mute may have changed.
  void refreshMute() => _applyMusic();

  bool get _musicAllowed =>
      !_disposed &&
      _musicWanted &&
      !muted &&
      _appVisible &&
      (!_requiresUserInput || _userInteracted);

  void _applyMusic() {
    final music = _music;
    if (music == null) return;
    try {
      if (!_musicAllowed) {
        if (_musicPlaying) {
          _musicPlaying = false;
          if (_musicWanted && !_disposed) {
            music.pause();
          } else {
            music.stop();
            _musicStarted = false;
          }
        } else if (!_musicWanted && _musicStarted) {
          music.stop();
          _musicStarted = false;
        }
        return;
      }
      if (_musicPlaying || _musicStarting) return;
      _musicStarting = true;
      final started = _musicStarted
          ? music.resume()
          : music.start(musicAsset, musicVolume);
      started.then<bool>((ok) => ok, onError: (Object _) => false).then((ok) {
        _musicStarting = false;
        if (!ok) return;
        _musicStarted = true;
        _musicPlaying = true;
        // State may have changed while playback was starting.
        _applyMusic();
      });
    } catch (_) {
      // Music is optional and must never break the game.
      _musicStarting = false;
    }
  }

  @override
  void dispose() {
    if (_disposed) return;
    _disposed = true;
    _musicWanted = false;
    try {
      _music?.stop();
    } catch (_) {}
    _musicPlaying = false;
    try {
      _player.dispose();
    } catch (_) {}
    super.dispose();
  }
}
